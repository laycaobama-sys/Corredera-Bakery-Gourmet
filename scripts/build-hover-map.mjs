/**
 * Lists the installed second photos (<id>-alt.jpg) in shared/productHoverPhotos.ts,
 * so product cards only try to fade in a photo that really exists.
 *
 *   node scripts/build-hover-map.mjs
 */
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const dir = path.join(root, "client/public/assets/products");
const files = fs.readdirSync(dir);
const map = {};
for (const f of files) {
  const m = f.match(/^(.+)-alt\.jpg$/);
  if (m && m[1] !== "ao") map[m[1]] = `${m[1]}-alt`;
}
// All olive oils share one serving photo.
if (files.includes("ao-alt.jpg")) {
  for (const f of files) {
    const m = f.match(/^(ao\d+)\.jpg$/);
    if (m) map[m[1]] = "ao-alt";
  }
}
const body = Object.keys(map)
  .sort((a, b) => a.localeCompare(b, "en", { numeric: true }))
  .map((id) => `  ${JSON.stringify(id)}: ${JSON.stringify(map[id])},`)
  .join("\n");
fs.writeFileSync(
  path.join(root, "shared/productHoverPhotos.ts"),
  `// Generated by scripts/build-hover-map.mjs: second photo of each product (fades in on hover, joins the gallery).\nexport const PRODUCT_HOVER_PHOTOS: Record<string, string> = {\n${body}\n};\n`,
);
console.log(`${Object.keys(map).length} productos con segunda foto`);
