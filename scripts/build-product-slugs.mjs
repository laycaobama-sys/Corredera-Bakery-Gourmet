/**
 * Writes shared/productSlugs.ts: the stable keyword URL of each product.
 * Existing slugs are never recalculated, so a renamed product keeps its address.
 *
 *   node scripts/build-product-slugs.mjs
 */
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const out = path.join(root, "shared/productSlugs.ts");
const { products } = JSON.parse(fs.readFileSync(path.join(root, "server/data/catalog-store.json"), "utf8"));

const existing = {};
if (fs.existsSync(out)) {
  for (const m of fs.readFileSync(out, "utf8").matchAll(/"([^"]+)": "([^"]+)"/g)) existing[m[1]] = m[2];
}

const slugify = (name) =>
  name
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/%/g, " ")
    .replace(/&/g, " y ")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");

const map = { ...existing };
const used = new Set(Object.values(map));
for (const p of products) {
  if (map[p.id]) continue;
  let slug = slugify(p.name);
  if (used.has(slug)) slug = `${slug}-${p.id}`;
  map[p.id] = slug;
  used.add(slug);
}

const body = Object.keys(map)
  .sort((a, b) => a.localeCompare(b, "en", { numeric: true }))
  .map((id) => `  ${JSON.stringify(id)}: ${JSON.stringify(map[id])},`)
  .join("\n");
fs.writeFileSync(
  out,
  `// Generated by scripts/build-product-slugs.mjs. Slugs are permanent: changing one breaks indexed links.\nexport const PRODUCT_SLUGS: Record<string, string> = {\n${body}\n};\n`,
);
console.log(`${Object.keys(map).length} URLs de producto`);
